/**
 * Build-time bake of the Sanity `errorPage` singleton into a static module the
 * error boundaries can import.
 *
 * Why build-time: Next.js error boundaries (app/error.tsx, app/global-error.tsx)
 * must be Client Components and must stay resilient — if the server is erroring,
 * Sanity may be the cause, so they can't fetch at error time. Instead we read the
 * content once at build and write app/error-content.ts. Edits in the Studio go
 * live on the next deploy.
 *
 * Fail-soft by design: any problem (no env, Sanity unreachable, no document)
 * writes the built-in DEFAULTS and exits 0, so the build never breaks.
 *
 * Runs via the `prebuild` npm hook. Run manually with:
 *   node scripts/generate-error-content.mjs
 */

import {existsSync, readFileSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'
import {createClient} from '@sanity/client'

const ROOT = process.cwd()

// Load .env.local for local runs; on Vercel the env vars are already present.
const envPath = join(ROOT, '.env.local')
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
    if (match && !process.env[match[1]]) {
      process.env[match[1]] = match[2].replace(/^["']|["']$/g, '')
    }
  }
}

// Keep these in sync with sanity/schemas/singletons/errorPage.ts initialValues.
const DEFAULTS = {
  eyebrow: 'Error',
  headline: 'Something went wrong.',
  message: "Give it another try — or head home and we'll meet you there.",
  retryButtonText: 'Try again',
  homeButtonText: 'Back home',
  homeButtonLink: '/',
}

const FIELDS = Object.keys(DEFAULTS)
const OUT = join(ROOT, 'app', 'error-content.ts')

function write(content, source) {
  const banner =
    '// GENERATED by scripts/generate-error-content.mjs — do not edit by hand.\n' +
    '// Baked at build time from the Sanity `errorPage` singleton; edits go live on the next deploy.\n\n'
  const body = `export const ERROR_PAGE_CONTENT = ${JSON.stringify(content, null, 2)} as const\n`
  writeFileSync(OUT, banner + body)
  console.log(`✓ app/error-content.ts written (${source})`)
}

async function fetchContent() {
  const projectId = process.env.NEXT_PUBLIC_SANITY_PROJECT_ID
  const dataset = process.env.NEXT_PUBLIC_SANITY_DATASET || 'production'
  if (!projectId) return null

  const client = createClient({
    projectId,
    dataset,
    apiVersion: '2025-02-27',
    useCdn: true,
    perspective: 'published',
  })

  return client.fetch(`*[_type == "errorPage"][0]{${FIELDS.join(', ')}}`)
}

try {
  const remote = await fetchContent()
  const merged = {...DEFAULTS}
  for (const key of FIELDS) {
    if (remote && remote[key]) merged[key] = remote[key]
  }
  write(merged, remote ? 'from Sanity' : 'defaults — no env/content')
} catch (err) {
  console.warn(`! error-content generation fell back to defaults: ${err.message}`)
  write(DEFAULTS, 'defaults — fetch failed')
}
